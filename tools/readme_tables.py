"""Regenerate the results tables of README.md from the result CSVs (no hand-typed numbers).

  python tools/readme_tables.py            # rewrites the block between <!-- RESULTS:BEGIN --> and <!-- RESULTS:END -->

Sources: results/final/table1_reconstruction.csv (BiMa-SR vs the strongest linear baseline, every configuration),
results/final/sr_overall.csv (lead-II model comparison), results/final/table2_classifier.csv (judge macro AUROC).
"""
import os
import sys

import pandas as pd

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
from bima_ecgsr import config as CFG  # noqa: E402

FIN = os.path.join(REPO, "results", "final")
COHORTS = [("ptbxl_test", "PTB-XL test"), ("georgia", "Georgia"), ("china", "China")]
SPEC2LABEL = {spec: label for label, spec, _ in CFG.CONFIGS}
BASE = {"linear_fir": "linear FIR", "einthoven_fir": "Einthoven/Goldberger + FIR"}
METHODS = {"bima_sr": "BiMa-SR", "dibima_sr_onestep": "DiBiMa-SR one-step", "dibima_sr_ddim6": "DiBiMa-SR DDIM-6",
           "linear_fir": "linear FIR", "einthoven_fir": "Einthoven/Goldberger + FIR", "true_12lead": "real 12-lead"}
BEGIN, END = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"


def ci(p, lo, hi):
    return f"{p:.3f} ({lo:.3f}-{hi:.3f})"


def table_recon(group):
    t = pd.read_csv(os.path.join(FIN, "table1_reconstruction.csv"))
    hdr = "| input leads | baseline | " + " | ".join(f"{n} BiMa-SR | {n} baseline" for _, n in COHORTS) + " |"
    rows = [hdr, "|" + "---|" * (2 + 2 * len(COHORTS))]
    for label, spec, _ in CFG.CONFIGS:
        sub = t[t.config == spec].set_index("cohort")
        cells = []
        for c, _ in COHORTS:
            r = sub.loc[c]
            cells += [ci(r[f"bima_{group}_pcc"], r[f"bima_{group}_lo"], r[f"bima_{group}_hi"]),
                      ci(r[f"base_{group}_pcc"], r[f"base_{group}_lo"], r[f"base_{group}_hi"])]
        rows.append(f"| {label} | {BASE[sub.iloc[0].baseline]} | " + " | ".join(cells) + " |")
    return "\n".join(rows)


def table_lead2():
    s = pd.read_csv(os.path.join(FIN, "sr_overall.csv"))
    s = s[(s.config == "II") & (s.group == "all_pred")]
    meths = [m for m in METHODS if m in set(s.method)]
    rows = ["| cohort (windows) | " + " | ".join(METHODS[m] for m in meths) + " |", "|" + "---|" * (1 + len(meths))]
    for c, n in COHORTS:
        sub = s[s.cohort == c].set_index("method")
        rows.append(f"| {n} ({int(sub.n_windows.iloc[0]):,}) | "
                    + " | ".join(ci(sub.loc[m, "pcc_pooled_median"], sub.loc[m, "pcc_ci_low"], sub.loc[m, "pcc_ci_high"]) for m in meths) + " |")
    return "\n".join(rows)


def table_cls():
    t = pd.read_csv(os.path.join(FIN, "table2_classifier.csv"))
    meths = ["true_12lead", "bima_sr", "dibima_sr_onestep", "einthoven_fir", "linear_fir"]
    out = []
    blocks = [("ptbxl_test", "superclass", "PTB-XL test, 5 diagnostic superclasses"),
              ("ptbxl_test", "panel", "PTB-XL test, 12-label panel"), ("georgia", "panel", "Georgia, 12-label panel"),
              ("china", "panel", "China, 12-label panel")]
    hdr = "| input leads | " + " | ".join(METHODS[m] for m in meths) + " |"
    for c, g, title in blocks:
        sub = t[(t.cohort == c) & (t.group == g)].set_index("config")
        out += [f"*{title}*", "", hdr, "|" + "---|" * (1 + len(meths))]
        for label, spec, _ in CFG.CONFIGS:
            r = sub.loc[spec]
            out.append(f"| {label} | " + " | ".join("—" if pd.isna(r[m]) else f"{r[m]:.3f}" for m in meths) + " |")
        out.append("")
    return "\n".join(out).rstrip()


def block():
    return "\n".join([
        BEGIN,
        "<!-- generated by tools/readme_tables.py from results/final/*.csv; do not edit by hand -->",
        "",
        "### Reconstruction fidelity, all six input configurations",
        "",
        "Pooled median Pearson correlation (PCC) over all predicted leads, 95% record-bootstrap CI (B = 1,000), BiMa-SR vs "
        "the strongest linear baseline of each configuration (`results/final/table1_reconstruction.csv`):",
        "",
        table_recon("all_pred"),
        "",
        "Precordial predicted leads only (V1-V6 minus measured inputs):",
        "",
        table_recon("prec_pred"),
        "",
        "### Lead-II input: regression vs diffusion (`results/final/sr_overall.csv`)",
        "",
        table_lead2(),
        "",
        "### Diagnostic readability (`results/final/table2_classifier.csv`)",
        "",
        "Record-level macro AUROC of the 12-lead judge (trained on real PTB-XL ECGs only) on real and reconstructed ECGs:",
        "",
        table_cls(),
        END])


def main():
    p = os.path.join(REPO, "README.md")
    s = open(p).read()
    if BEGIN not in s:
        sys.exit(f"markers {BEGIN} / {END} not found in README.md")
    s = s[:s.index(BEGIN)] + block() + s[s.index(END) + len(END):]
    open(p, "w").write(s)
    print("README.md results block regenerated")


if __name__ == "__main__":
    main()
