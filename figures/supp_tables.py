# ------------------------------------------------------------------ S2 classifier
lab = pd.read_csv(os.path.join(FIN, "cls_per_label_auroc.csv"))
SUPER = ["NORM", "MI", "STTC", "CD", "HYP"]
PANEL = ["AFIB", "AFLT", "1AVB", "PAC", "PVC", "SBRAD", "STACH", "WPW", "LVH", "RVH", "CRBBB", "CLBBB"]
judge = json.load(open(os.path.join(CFG.CLS_DIR, "judge12", "summary.json")))


def s2_block(coh, grp, labels):
    rows = []
    sub0 = lab[(lab.cohort == coh) & (lab.group == grp)]
    # real ECG once (identical for every configuration)
    entries = [("--", "true_12lead", "II")]
    for cfg in CONFIGS:
        for m in ["bima_sr", "dibima_sr_onestep", "linear_fir", "einthoven_fir"]:
            if not sub0[(sub0.config == cfg) & (sub0.input == m)].empty:
                entries.append((CLAB[cfg], m, cfg))
    real_all = sub0[sub0.input == "true_12lead"].groupby("label").auroc.agg(lambda s: s.max() - s.min())
    assert np.nanmax(real_all.values) < 1e-12
    last = None
    for clab, m, cfg in entries:
        s = sub0[(sub0.config == cfg) & (sub0.input == m)].set_index("label")
        mac = s.loc["macro"]
        vals = []
        for l in labels:
            r = s.loc[l]
            vals.append(f"{r.auroc:.3f}" if r.status == "ok" else "n.s.")
        if last is not None and clab != last:
            rows.append(r"\addlinespace[1pt]")
        rows.append(f"{clab if clab != last else ''} & {MNAME[m]} & {ci(mac.auroc, mac.ci_low, mac.ci_high)} & "
                    + " & ".join(vals) + r"\\")
        last = clab
    return rows


def ncount(coh, grp, labels):
    s = lab[(lab.cohort == coh) & (lab.group == grp) & (lab.input == "true_12lead") & (lab.config == "II")].set_index("label")
    return " & ".join(num(s.loc[l].n_pos) if s.loc[l].status != "excluded_invalid_label" else "--" for l in labels)


